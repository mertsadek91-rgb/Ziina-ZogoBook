export function useAcc() {
  const { lang } = useI18n();
  const a = lang === "ar" ? AR : EN;
  const categoryLabel = (key?: string | null) => {
    const c = EXPENSE_CATEGORIES.find((x) => x.key === key);
    return c ? c[lang] : key || "—";
  };
  const kindLabel = (k: string) => (a[`entry_${k}` as keyof Dict] as string) ?? k;
  const accountKindLabel = (k: string) => (a[`kind_${k}` as keyof Dict] as string) ?? k;
  return { a, lang, categoryLabel, kindLabel, accountKindLabel };
}
